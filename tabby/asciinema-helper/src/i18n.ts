export function registerPluginTranslations(translate: TranslateService): void {
    try {
        const store = (translate as any)?.store
        if (store) {
            if (!store.translations) {
                store.translations = {}
            }
            for (const lang of ['en-US', 'ko-KR', 'ko']) {
                const pluginTrans = translations[lang] || translations['en-US']
                store.translations[lang] = Object.assign({}, store.translations[lang] || {}, pluginTrans)
            }
        } else {
            for (const lang of ['en-US', 'ko-KR', 'ko']) {
                const pluginTrans = translations[lang] || translations['en-US']
                const existing = (translate as any).translations?.[lang] || {}
                if (Object.keys(existing).length > 0) {
                    translate.setTranslation(lang, Object.assign({}, existing, pluginTrans), true)
                }
            }
        }
    } catch (e) {
        console.error('Asciinema plugin failed to register translations:', e)
    }
}
